// TestJudgeBodyMatchesTheGate ties JudgeBody to the attribution gate's body arm,
// the one place a pull-request body's disclosure is decided: the gate runs in CI
// without Go, so the two share a test rather than code. Every body in the corpus
// goes through the gate itself, with its session-URL half stubbed clean, and
// JudgeBody must accept exactly the bodies the gate accepts.
func TestJudgeBodyMatchesTheGate(t *testing.T) {
	gate, err := filepath.Abs(filepath.Join("..", "..", "..", "scripts", "check-attribution.sh"))
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	// The gate delegates its session-URL half to `abcd lint outbound`; that half
	// is the guard's other check, so a stub that clears everything leaves the
	// disclosure half alone deciding.
	stub := filepath.Join(dir, "outbound-clean")
	if err := os.WriteFile(stub, []byte("#!/bin/sh\nexit 0\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	for name, body := range bodyCorpus {
		t.Run(name, func(t *testing.T) {
			f := filepath.Join(dir, "body.md")
			if err := os.WriteFile(f, []byte(body), 0o644); err != nil {
				t.Fatal(err)
			}
			cmd := exec.Command("bash", gate, "body", f)
			cmd.Dir = dir
			cmd.Env = append(os.Environ(), "ABCD_OUTBOUND_BIN="+stub)
			out, err := cmd.CombinedOutput()
			gateAccepts := err == nil
			if ee, ok := err.(*exec.ExitError); err != nil && (!ok || ee.ExitCode() != 1) {
				t.Fatalf("the gate could not judge the body: %v\n%s", err, out)
			}
			fault := JudgeBody(body)
			if got := fault == BodyClean; got != gateAccepts {
				t.Fatalf("JudgeBody(%q) = %v, but the gate %s it:\n%s", body, fault, map[bool]string{true: "accepts", false: "refuses"}[gateAccepts], out)
			}
		})
	}
}

// TestJudgeBodyNamesTheFirstFault: the fault reported is the one the gate
// reports, in the gate's order (a footer, then a co-author, then a malformed
// label, then no trailer at all), so the remedy handed back is the right one.
func TestJudgeBodyNamesTheFirstFault(t *testing.T) {
	for _, tc := range []struct {
		body string
		want BodyFault
	}{
		{"Assisted-by: Claude:x", BodyClean},
		{"🤖 Generated with [X](y)\nCo-authored-by: A", BodyGeneratedFooter},
		{"Co-authored-by: A\nAssisted-by: abcd:latest", BodyCoAuthor},
		{"Assisted-by: abcd:latest", BodyMalformedLabel},
		{"Summary", BodyNoTrailer},
	} {
		if got := JudgeBody(tc.body); got != tc.want {
			t.Errorf("JudgeBody(%q) = %v, want %v", tc.body, got, tc.want)
		}
	}
}

// TestBodyRefusalPatternsAreTheGates: the footer and co-author patterns are the
// gate's GENERATED_RE and COAUTHOR_RE, read out of the script.
func TestBodyRefusalPatternsAreTheGates(t *testing.T) {
	if got := gateAssignment(t, "GENERATED_RE"); got != generatedFooterPattern {
		t.Errorf("the gate's GENERATED_RE is\n\t%s\nbut internal/core/assistedby reads\n\t%s\none of the two moved alone", got, generatedFooterPattern)
	}
	if got := gateAssignment(t, "COAUTHOR_RE"); got != coAuthorPattern {
		t.Errorf("the gate's COAUTHOR_RE is\n\t%s\nbut internal/core/assistedby reads\n\t%s\none of the two moved alone", got, coAuthorPattern)
	}
	if got, want := gateAssignment(t, "NONE_RE"), `^Assisted-by: [Nn]one$`; got != want {
		t.Errorf("the gate's NONE_RE is\n\t%s\nbut internal/core/assistedby reads\n\t%s\none of the two moved alone", got, want)
	}
}
